// Cost estimation (M17). Amounts are decimal strings rounded to cents; null means not estimated.
export type ExternalDataDisclosure = {
  provider: string;
  providerName: string;
  version: string;
  externalCalls: boolean;
  offline: boolean;
  endpoint: string;
  reads: string[];
  sentOffDevice: string[];
  neverSent: string[];
  authentication: string;
  storage: string;
  documentation: string;
};
export type CostProviderState = 'strict_local' | 'cli_missing' | 'off' | 'ready' | 'unavailable';
export type CostProviderCapabilities = {
  provider: string;
  state: CostProviderState;
  installed: boolean;
  enabled: boolean;
  canEstimate: boolean;
  reason?: string;
  cliVersion?: string;
  optedInAt?: string;
  strictLocal: boolean;
  offlineAvailable: boolean;
  disclosure?: ExternalDataDisclosure;
};
export type CostItemStatus = 'estimated' | 'partial' | 'usage_unknown' | 'unsupported' | 'free' | 'not_estimated';
export type CostComponent = { name: string; unit: string; monthlyQuantity: string | null; price: string | null; monthlyCost: string | null; usageBased?: boolean };
export type CostLineItem = {
  address: string;
  resourceType: string;
  action: string;
  status: CostItemStatus;
  pastMonthly: string | null;
  monthly: string | null;
  delta: string | null;
  unpricedComponents: number;
  components: CostComponent[];
  note?: string;
};
export type CostTypeSummary = { resourceType: string; count: number; estimated: number; notEstimated: number; delta: string | null };
export type EstimateCoverage = {
  changed: number;
  costBearing: number;
  estimated: number;
  partial: number;
  usageUnknown: number;
  unsupported: number;
  free: number;
  notEstimated: number;
  percent: number | null;
  unsupportedTypes: Record<string, number>;
};
export type CostCaveat = { code: string; message: string; count?: number };
export type CostBreakdown = {
  currency: string;
  monthlyDelta: string;
  addedMonthly: string;
  removedMonthly: string;
  changedDelta: string;
  pastMonthly: string;
  projectedMonthly: string;
  coverage: EstimateCoverage;
  caveats: CostCaveat[];
  types: CostTypeSummary[];
  items: CostLineItem[];
  truncated: boolean;
};
export type CostEstimate = {
  id: string;
  planId: string;
  status: 'running' | 'completed' | 'failed' | 'cancelled';
  error?: { code: string; message: string };
  startedAt: string;
  finishedAt?: string;
  provider: string;
  providerVersion?: string;
  pricingSource: string;
  basis: string;
  workspace: string;
  engine: string;
  fingerprint: string;
  artifactDigest: string;
  cancelRequested: boolean;
  stale: boolean;
  staleReason?: string;
  breakdown?: CostBreakdown;
  historyWarning?: string;
};
export type CostAggregate = {
  id: string;
  projectKey: string;
  projectName: string;
  workspace: string;
  engine: string;
  planId: string;
  fingerprint: string;
  createdAt: string;
  provider: string;
  currency: string;
  monthlyDelta: string;
  pastMonthly: string;
  projectedMonthly: string;
  coveragePercent: number | null;
  changed: number;
  estimated: number;
  notEstimated: number;
  providerVersion: string;
  pricingSource: string;
};
